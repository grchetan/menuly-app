/**
 * Application Security & Defensive Sanitization Suite
 * Protects against XSS, Prototype Pollution, IDOR price manipulation, and data injection.
 */

// Regex patterns for validation
const SAFE_HEX_COLOR = /^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;
const SAFE_RGB_COLOR = /^rgba?\(\s*\d+\s*,\s*\d+\s*,\s*\d+(\s*,\s*(0|1|0?\.\d+))?\s*\)$/i;
const SAFE_HSL_COLOR = /^hsla?\(\s*\d+\s*,\s*\d+%\s*,\s*\d+%(\s*,\s*(0|1|0?\.\d+))?\s*\)$/i;

/**
 * Strips dangerous HTML tags and script injection vectors from string input.
 */
export function sanitizeText(val: unknown, maxLen = 250): string {
  if (val === null || val === undefined) return "";
  const str = String(val).trim();
  if (!str) return "";

  // Strip script tags, HTML tags, and event handlers
  const cleaned = str
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/<[^>]+>/g, "")
    .replace(/javascript:/gi, "")
    .replace(/on\w+\s*=/gi, "")
    // Remove control characters except standard whitespace
    .replace(/[\u0000-\u0008\u000B-\u000C\u000E-\u001F\u007F-\u009F]/g, "");

  return cleaned.slice(0, maxLen);
}

/**
 * Validates and normalizes price to prevent negative prices, NaN, or overflow.
 * Enforces: 0 <= price <= 100,000 INR, rounded to 2 decimal places.
 */
export function sanitizePrice(val: unknown): number {
  if (val === null || val === undefined) return 0;
  const num = typeof val === "number" ? val : Number(val);
  if (!Number.isFinite(num) || Number.isNaN(num)) return 0;
  // Ensure non-negative and capped at 1 Lakh
  const clamped = Math.min(100_000, Math.max(0, num));
  return Math.round(clamped * 100) / 100;
}

/**
 * Validates image URL to prevent XSS via javascript: or data:text/html payloads.
 * Only allows trusted schemes: http, https, data:image/ (webp, png, jpeg, svg), or relative URLs.
 */
export function sanitizeUrl(val: unknown): string | null {
  if (!val || typeof val !== "string") return null;
  const trimmed = val.trim();
  if (!trimmed) return null;

  // Relative path
  if (trimmed.startsWith("/") && !trimmed.startsWith("//")) {
    return trimmed.slice(0, 500);
  }

  // HTTP or HTTPS
  if (/^https?:\/\//i.test(trimmed)) {
    try {
      const parsed = new URL(trimmed);
      if (parsed.protocol === "http:" || parsed.protocol === "https:") {
        return parsed.href.slice(0, 2000);
      }
    } catch {
      return null;
    }
  }

  // Safe data:image URIs (generated by Menuly image compressor)
  if (/^data:image\/(png|jpeg|jpg|webp|svg\+xml);base64,/i.test(trimmed)) {
    // Check maximum payload limit (1.5MB for data URL)
    if (trimmed.length > 2_000_000) return null;
    return trimmed;
  }

  return null;
}

/**
 * Validates and sanitizes color strings to prevent CSS injection.
 */
export function sanitizeColor(val: unknown, fallback = "#0f5132"): string {
  if (!val || typeof val !== "string") return fallback;
  const trimmed = val.trim();
  if (
    SAFE_HEX_COLOR.test(trimmed) ||
    SAFE_RGB_COLOR.test(trimmed) ||
    SAFE_HSL_COLOR.test(trimmed)
  ) {
    return trimmed;
  }
  return fallback;
}

/**
 * Validates and normalizes email addresses.
 */
export function sanitizeEmail(val: unknown): string {
  if (!val || typeof val !== "string") return "";
  const cleaned = val.trim().toLowerCase().slice(0, 150);
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return emailRegex.test(cleaned) ? cleaned : "";
}

/**
 * Validates and normalizes phone numbers.
 */
export function sanitizePhone(val: unknown): string | null {
  if (!val || typeof val !== "string") return null;
  // Allow digits, spaces, plus, hyphens, parentheses
  const cleaned = val.replace(/[^\d+() -]/g, "").trim().slice(0, 30);
  return cleaned || null;
}

/**
 * Deep cleans an object from Prototype Pollution keys (__proto__, constructor, prototype).
 */
export function sanitizeObject<T>(obj: T): T {
  if (!obj || typeof obj !== "object") return obj;

  if (Array.isArray(obj)) {
    return obj.map((item) => sanitizeObject(item)) as unknown as T;
  }

  const clean: Record<string, any> = Object.create(null);
  for (const key of Object.keys(obj as any)) {
    if (key === "__proto__" || key === "constructor" || key === "prototype") {
      continue;
    }
    clean[key] = sanitizeObject((obj as any)[key]);
  }

  return { ...clean } as T;
}
